// Command genfont rasterizes the label fonts into components/label/font_data.c.
//
//	cd tools/genfont && go run . > ../../components/label/font_data.c
package main

import (
	"fmt"
	"os"
	"strings"

	"golang.org/x/image/font"
	"golang.org/x/image/font/gofont/gobold"
	"golang.org/x/image/font/gofont/gomonobold"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/math/fixed"
)

const (
	firstChar = 32
	lastChar  = 126
)

type spec struct {
	name string
	ttf  []byte
	px   float64
}

var specs = []spec{
	{"large", gobold.TTF, 80},
	{"medium", gobold.TTF, 54},
	{"small", gobold.TTF, 36},
	{"caption", gomonobold.TTF, 36},
}

func main() {
	var out strings.Builder
	out.WriteString("// Generated by tools/genfont. Do not edit.\n\n#include \"font.h\"\n\n")
	for _, s := range specs {
		if err := emit(&out, s); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	fmt.Print(out.String())
}

func emit(out *strings.Builder, s spec) error {
	f, err := opentype.Parse(s.ttf)
	if err != nil {
		return err
	}
	face, err := opentype.NewFace(f, &opentype.FaceOptions{Size: s.px, DPI: 72, Hinting: font.HintingFull})
	if err != nil {
		return err
	}
	defer face.Close()
	m := face.Metrics()

	var bits []byte
	var glyphs strings.Builder
	for r := rune(firstChar); r <= lastChar; r++ {
		dr, mask, maskp, adv, ok := face.Glyph(fixed.P(0, 0), r)
		if !ok {
			return fmt.Errorf("%s has no glyph for %q", s.name, r)
		}
		w, h := dr.Dx(), dr.Dy()
		off := len(bits)
		rowBytes := (w + 7) / 8
		buf := make([]byte, rowBytes*h)
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				_, _, _, a := mask.At(maskp.X+x, maskp.Y+y).RGBA()
				if a >= 0x8000 {
					buf[y*rowBytes+x/8] |= 0x80 >> (x % 8)
				}
			}
		}
		bits = append(bits, buf...)
		fmt.Fprintf(&glyphs, "    {%d, %d, %d, %d, %d, %d}, // %q\n", off, w, h, dr.Min.X, dr.Min.Y, adv.Round(), r)
	}

	fmt.Fprintf(out, "static const glyph_t %s_glyphs[] = {\n%s};\n\n", s.name, glyphs.String())
	fmt.Fprintf(out, "static const uint8_t %s_bits[] = {", s.name)
	for i, b := range bits {
		if i%16 == 0 {
			out.WriteString("\n   ")
		}
		fmt.Fprintf(out, " 0x%02x,", b)
	}
	out.WriteString("\n};\n\n")
	fmt.Fprintf(out, "const font_t font_%s = {%d, %d, %s_glyphs, %s_bits};\n\n",
		s.name, m.Ascent.Ceil(), m.Descent.Ceil(), s.name, s.name)
	return nil
}
